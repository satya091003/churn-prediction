"""
preprocessing.py
-----------------
Load and clean the raw churn CSV. Works with either the synthetic dataset
generated by data/generate_data.py or the real Kaggle Telco Churn CSV
(same column names).
"""

import pandas as pd


def load_data(path="data/telco_churn.csv"):
    df = pd.read_csv(path)
    return df


def clean_data(df):
    df = df.copy()

    # TotalCharges is sometimes read as a string with blanks in the real
    # Kaggle dataset (new customers with tenure 0) -> coerce and fill
    df["TotalCharges"] = pd.to_numeric(df["TotalCharges"], errors="coerce")
    df["TotalCharges"] = df["TotalCharges"].fillna(df["MonthlyCharges"] * df["tenure"])

    # Drop ID column, not predictive
    if "customerID" in df.columns:
        df = df.drop(columns=["customerID"])

    # Target to binary
    df["Churn"] = df["Churn"].map({"Yes": 1, "No": 0})

    # Standardize the "No internet/phone service" categories to "No" so
    # one-hot encoding doesn't create noisy sparse columns
    service_cols = [
        "MultipleLines", "OnlineSecurity", "OnlineBackup", "DeviceProtection",
        "TechSupport", "StreamingTV", "StreamingMovies"
    ]
    for col in service_cols:
        if col in df.columns:
            df[col] = df[col].replace(
                {"No internet service": "No", "No phone service": "No"}
            )

    return df


if __name__ == "__main__":
    raw = load_data()
    cleaned = clean_data(raw)
    print(cleaned.info())
    print(cleaned["Churn"].value_counts(normalize=True))
